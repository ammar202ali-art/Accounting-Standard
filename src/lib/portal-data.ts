export type Job = typeof jobs[number];
export const ALL_FILTERS = 'الكل';
export type JobFilters = { location: string; role: string; type: string };
export const defaultJobFilters: JobFilters = { location: ALL_FILTERS, role: ALL_FILTERS, type: ALL_FILTERS };
const uniqueValues = (values: string[]) => [ALL_FILTERS, ...Array.from(new Set(values))];
export const jobLocations = uniqueValues(jobs.map(j => j.location));
export const jobRoles = uniqueValues(jobs.map(j => j.role));
export const jobTypes = uniqueValues(jobs.map(j => j.employmentType));
export function jobOptions(list: Job[]) {
 return { locations: uniqueValues(list.map(j => j.location)), roles: uniqueValues(list.map(j => j.role)), types: uniqueValues(list.map(j => j.employmentType)) };
}
export function filterJobs(filters: JobFilters, list: Job[] = jobs) {
 return list.filter(j => (filters.location === ALL_FILTERS || j.location === filters.location) && (filters.role === ALL_FILTERS || j.role === filters.role) && (filters.type === ALL_FILTERS || j.employmentType === filters.type));
}
export const getJob = (id: string, list: Job[] = jobs) => list.find(j => String(j.id) === id);
export const relatedJobs = (job: Job, list: Job[] = jobs) => list.filter(j => j.id !== job.id && (j.role === job.role || j.location === job.location)).slice(0, 3);
